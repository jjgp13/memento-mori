/**
 * The wisdom library: quotes, short stories and practices from people who lived before us.
 * Schema, sources and selection rules: docs/wisdom.md. Pure data (no runtime imports), shaped like the
 * rows a future `daily_content` table would hold, so a sync can add to it without changing the app.
 *
 * Rules for every entry:
 * - Quotes are verbatim from a public-domain translation listed in SOURCES, checked against the text
 *   and cited to the exact book, letter, chapter or verse. `modern` (optional) is our light update of
 *   archaic English ("thou" → "you"); it never changes the meaning.
 * - Stories and practices are retold in our own words, with the passage they retell cited.
 * - Anything that reminds people of death carries an `action`: one small thing they could do today.
 */
