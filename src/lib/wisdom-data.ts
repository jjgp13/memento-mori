export type Wisdom = {
  /** Stable forever: used for "seen" history on the device and as the row key when syncing. */
  id: string;
  type: WisdomType;
  /** Quote: exactly as the translation has it. Story or practice: our own words. */
  text: string;
  /** Quote in older English, gently brought up to date. Shown in the app when present. */
  modern?: string;
  author: AuthorKey;
  work: string;
  /** Exact place: book.section, letter.section, chapter, chapter:verse. */
  locus: string;
  source: SourceKey;
  /** 'public-domain': `text` quotes a public-domain translation. 'own-words': we retold it. */
  licence: 'public-domain' | 'own-words';
  themes: Theme[];
  /** Which of the person's values (src/lib/values.ts) this speaks to; picked more often for them. */
  values?: ValueKey[];
  /** A question to sit with today. `{day}` becomes the weekday. */
  question: string;
  /**
   * One small thing to do today, finishing the sentence "You could …". Required with 'mortality'
   * (docs/nudges.md §1g). `{person}` becomes someone they love, or "someone you love".
   */
  action?: string;
};

